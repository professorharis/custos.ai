'use client';

import React from 'react';
import { getDossierReportId } from '@/lib/scannerHelpers';
import type { ScamResult } from '@/lib/types';

// Professional, clean sans-serif font for everything
const FONT_CLEAN = "'Inter', ui-sans-serif, system-ui, -apple-system, sans-serif";

interface KeywordFinding {
  heading: string;
  content: string;
}

export type DocumentViewResult = ScamResult & {
  findings?: KeywordFinding[];
  threatType?: string;
  attemptLabel?: string;
  recommendation?: string;
};

interface DocumentViewProps {
  result: DocumentViewResult;
  inputContent: string;
  inputType: string;
}

function formatDate(date: Date): string {
  const options: Intl.DateTimeFormatOptions = {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    hour: 'numeric',
    minute: '2-digit',
    hour12: true,
  };
  return date.toLocaleDateString('en-US', options);
}

function extractRecommendationBullets(text: string): string[] {
  const lines = text
    .split(/\r?\n/)
    .map((l) => l.replace(/^[\s\-•]+/, '').trim())
    .filter(Boolean);

  if (lines.length > 1) return lines;

  return text
    .split('.')
    .map((s) => s.trim())
    .filter(Boolean)
    .map((s) => s + '.');
}

export function DocumentView({ result, inputContent, inputType }: DocumentViewProps) {
  const reportId = getDossierReportId(result.scanId);
  const now = new Date();
  const dateTimeStr = formatDate(now);

  // Determine the threat label
  const threatLabel =
    (result.attemptLabel && result.attemptLabel.trim()) ||
    (result.threatType && result.threatType.trim()) ||
    'Threat Detected';

  const scanTypeLabel = (inputType || 'text').toUpperCase();
  const bullets = result.recommendation ? extractRecommendationBullets(result.recommendation) : [];

  return (
    <div
      className="max-w-[720px] mx-auto bg-white text-black px-10 py-12"
      style={{ fontFamily: FONT_CLEAN, fontSize: '14px', lineHeight: '1.7', color: '#1a1a1a' }}
    >
      {/* ─── HEADER ──────────────────────────────────────────────────── */}
      <div className="text-center border-b border-black/10 pb-6 mb-7">
        {/* Main Title */}
        <h1
          className="text-[22px] font-bold text-black leading-tight tracking-tight"
          style={{ fontFamily: FONT_CLEAN }}
        >
          Security Analysis Report
        </h1>

        {/* Generated by / datetime */}
        <p
          className="text-[12.5px] text-black/50 mt-1.5"
          style={{ fontFamily: FONT_CLEAN }}
        >
          Generated by Custos AI &nbsp;·&nbsp; {dateTimeStr}
        </p>

        {/* ── Threat Label – standalone row ── */}
        <p
          className="text-[16px] font-bold text-gray-600 mt-4"
          style={{ fontFamily: FONT_CLEAN }}
        >
          {threatLabel}
        </p>

        {/* ── Metadata – separate row, smaller & muted ── */}
        <p
          className="text-[12.5px] text-black/60 mt-1.5"
          style={{ fontFamily: FONT_CLEAN }}
        >
          Report ID: {reportId} &nbsp;|&nbsp; Scan Type: {scanTypeLabel} &nbsp;|&nbsp; Risk Score: {result.riskScore}/100
        </p>
      </div>

      {/* ─── SCANNED CONTENT ────────────────────────────────────────── */}
      <div className="mb-6">
        <h2
          className="text-[16px] font-bold text-black mb-2"
          style={{ fontFamily: FONT_CLEAN }}
        >
          Scanned Content
        </h2>
        <p className="text-[14px] leading-7 text-black/90 whitespace-pre-wrap">
          {inputContent || '(no content provided)'}
        </p>
      </div>

      {/* ─── FINDINGS ────────────────────────────────────────────────── */}
      {(result.findings ?? []).map((f, i) => (
        <div key={i} className="mb-5">
          <h2
            className="text-[16px] font-bold text-black mb-1"
            style={{ fontFamily: FONT_CLEAN }}
          >
            {f.heading}
          </h2>
          <p className="text-[14px] leading-7 text-black/90">
            {f.content.replace(/\*\*/g, '')}
          </p>
        </div>
      ))}

      {/* ─── SUMMARY ────────────────────────────────────────────────── */}
      <div className="mb-6">
        <h2
          className="text-[16px] font-bold text-black mb-1"
          style={{ fontFamily: FONT_CLEAN }}
        >
          Summary
        </h2>
        <p className="text-[14px] leading-7 text-black/90">{result.explanation}</p>
      </div>

      {/* ─── RECOMMENDATION ────────────────────────────────────────── */}
      {bullets.length > 0 && (
        <div>
          <h2
            className="text-[16px] font-bold text-black mb-2"
            style={{ fontFamily: FONT_CLEAN }}
          >
            Recommendation
          </h2>
          <ul className="space-y-1.5">
            {bullets.map((b, i) => (
              <li key={i} className="text-[14px] leading-7 text-black/90 flex gap-2">
                <span className="flex-shrink-0">•</span>
                <span>{b}</span>
              </li>
            ))}
          </ul>
        </div>
      )}
    </div>
  );
}

export default DocumentView;